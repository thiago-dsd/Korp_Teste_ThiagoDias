/**
 * The shape `en-US.ts` is checked against: same nesting, same keys, but every
 * leaf widened to `string`. Without the widening, `as const` above would
 * force every other locale to contain this exact Portuguese sentence —
 * `satisfies` would be checking for a translation identical to the original,
 * which is the one thing a translation must not be.
 */
type Widen<T> = T extends string ? string : { readonly [K in keyof T]: Widen<T[K]> };
export type Translations = Widen<typeof ptBR>;
